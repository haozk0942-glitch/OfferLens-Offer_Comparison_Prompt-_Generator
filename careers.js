export function fitSignals(profile,offer){
 return traits.map(([key,name])=>{const wish=Number(profile[`wish_${key}`]),ability=Number(profile[`ability_${key}`]),demand=Number(offer[`demand_${key}`]);
 let signal='待补充';if(demand&&wish)signal=demand>=4&&wish<=2?'偏好冲突待讨论':demand>=4&&wish>=4?'兴趣方向一致':'需结合任务讨论';
 return {维度:name,愿意程度:wish||'未知',能力自述:ability||'未知',实际任务强度:demand||'未知',经历证据:profile[`evidence_${key}`]||'未提供',提示:signal};
 });
}
